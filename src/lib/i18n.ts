export function translate(locale: Locale, message: string, values: Record<string, string | number> = {}): string {
  const key = message.trim();
  if (!key) return message;
  const translated = locale === 'zh' && Object.hasOwn(chineseMessages, key) ? chineseMessages[key] : key;
  const content = translated.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values[name] === undefined ? placeholder : String(values[name])
  );
  return `${message.match(/^\s*/)?.[0] || ''}${content}${message.match(/\s*$/)?.[0] || ''}`;
}
