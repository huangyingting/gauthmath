export type Locale = 'en' | 'zh';
export interface LocalizedMessage {
  key: string;
  values?: Record<string, string | number>;
}
export const LOCALE_COOKIE = 'gauth-locale';

export function getPreferredLocale(saved: string | undefined, accepted: string | null): Locale {
  if (saved === 'en' || saved === 'zh') return saved;
  const languages = (accepted || '').split(',').map((entry) => {
    const [language, quality] = entry.trim().toLowerCase().split(';q=');
    return { language, quality: quality ? Number(quality) : 1 };
  }).sort((a, b) => b.quality - a.quality);
  for (const { language, quality } of languages) {
    if (quality <= 0) continue;
    if (/^zh(?:-|$)/.test(language)) return 'zh';
    if (/^en(?:-|$)/.test(language)) return 'en';
  }
  return 'en';
}

